window.translateI18n = function(lang, key, vars) {
  const dict = window.I18N_MESSAGES[lang] || window.I18N_MESSAGES.en;
  let raw = (dict && dict[key]) || window.I18N_MESSAGES.en[key] || key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, function(_, name) {
    return vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : "";
  });
};
